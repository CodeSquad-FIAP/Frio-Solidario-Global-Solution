-- FRIO SOLIDARIO - GLOBAL SOLUTION FIAP
-- Banco de dados: PostgreSQL 17
-- Criacao das 6 entidades do projeto

BEGIN;

-- 1. INSTITUICAO
CREATE TABLE instituicao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    cnpj CHAR(14) NOT NULL,
    tipo VARCHAR(10) NOT NULL,
    cidade VARCHAR(120) NOT NULL,
    endereco VARCHAR(255) NOT NULL,

    CONSTRAINT uq_instituicao_cnpj UNIQUE (cnpj),

    CONSTRAINT ck_instituicao_tipo
        CHECK (tipo IN ('BANCO', 'MERCADO', 'PADARIA')),

    CONSTRAINT ck_instituicao_cnpj_formato
        CHECK (cnpj ~ '^[0-9]{14}$')
);

-- 2. USUARIO
CREATE TABLE usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    email VARCHAR(254) NOT NULL,
    senha_hash VARCHAR(100) NOT NULL,
    papel VARCHAR(12) NOT NULL,
    instituicao_id BIGINT NOT NULL,

    CONSTRAINT uq_usuario_email UNIQUE (email),

    CONSTRAINT ck_usuario_papel
        CHECK (papel IN ('ADMIN', 'VOLUNTARIO')),

    CONSTRAINT fk_usuario_instituicao
        FOREIGN KEY (instituicao_id)
        REFERENCES instituicao (id)
        ON DELETE RESTRICT
);

-- 3. EQUIPAMENTO
CREATE TABLE equipamento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instituicao_id BIGINT NOT NULL,
    nome VARCHAR(150) NOT NULL,
    tipo VARCHAR(12) NOT NULL,
    temp_min NUMERIC(5,2) NOT NULL,
    temp_max NUMERIC(5,2) NOT NULL,
    umid_max NUMERIC(5,2) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT fk_equipamento_instituicao
        FOREIGN KEY (instituicao_id)
        REFERENCES instituicao (id)
        ON DELETE RESTRICT,

    CONSTRAINT ck_equipamento_tipo
        CHECK (tipo IN ('CAMARA', 'GELADEIRA', 'FREEZER')),

    CONSTRAINT ck_equipamento_faixa
        CHECK (temp_min < temp_max),

    CONSTRAINT ck_equipamento_temperatura_plausivel
        CHECK (
            temp_min BETWEEN -40 AND 80
            AND temp_max BETWEEN -40 AND 80
        ),

    CONSTRAINT ck_equipamento_umid_max
        CHECK (umid_max > 0 AND umid_max <= 100)
);

-- 4. LEITURA
CREATE TABLE leitura (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipamento_id BIGINT NOT NULL,
    temperatura NUMERIC(5,2) NOT NULL,
    umidade NUMERIC(5,2) NOT NULL,
    porta_aberta BOOLEAN NOT NULL,
    registrada_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    origem VARCHAR(10) NOT NULL,

    CONSTRAINT fk_leitura_equipamento
        FOREIGN KEY (equipamento_id)
        REFERENCES equipamento (id)
        ON DELETE RESTRICT,

    CONSTRAINT ck_leitura_temperatura
        CHECK (temperatura BETWEEN -40 AND 80),

    CONSTRAINT ck_leitura_umidade
        CHECK (umidade BETWEEN 0 AND 100),

    CONSTRAINT ck_leitura_origem
        CHECK (origem IN ('SENSOR', 'SIMULADO')),

    CONSTRAINT uq_leitura_id_equipamento
        UNIQUE (id, equipamento_id)
);

-- 5. ALERTA
CREATE TABLE alerta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipamento_id BIGINT NOT NULL,
    leitura_id BIGINT NOT NULL,
    tipo VARCHAR(14) NOT NULL,
    severidade VARCHAR(10) NOT NULL,
    status VARCHAR(10) NOT NULL DEFAULT 'ABERTO',
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resolvido_em TIMESTAMPTZ,
    resolvido_por_id BIGINT,
    -- O que o voluntário fez ao resolver. Opcional: alerta resolvido sem informar a ação fica NULL.
    acao_tomada VARCHAR(16),

    CONSTRAINT fk_alerta_equipamento
        FOREIGN KEY (equipamento_id)
        REFERENCES equipamento (id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_alerta_leitura_do_equipamento
        FOREIGN KEY (leitura_id, equipamento_id)
        REFERENCES leitura (id, equipamento_id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_alerta_usuario_resolucao
        FOREIGN KEY (resolvido_por_id)
        REFERENCES usuario (id)
        ON DELETE RESTRICT,

    CONSTRAINT ck_alerta_tipo
        CHECK (
            tipo IN (
                'TEMP_ALTA',
                'TEMP_BAIXA',
                'PORTA_ABERTA',
                'UMIDADE'
            )
        ),

    -- Valores provisórios 
    CONSTRAINT ck_alerta_severidade
        CHECK (
            severidade IN (
                'BAIXA', 'MEDIA', 'ALTA', 'CRITICA'
            )
        ),

    CONSTRAINT ck_alerta_status
        CHECK (status IN ('ABERTO', 'RESOLVIDO')),

    CONSTRAINT ck_alerta_resolucao_coerente
        CHECK (
            (
                status = 'ABERTO'
                AND resolvido_em IS NULL
                AND resolvido_por_id IS NULL
            )
            OR
            (
                status = 'RESOLVIDO'
                AND resolvido_em IS NOT NULL
                AND resolvido_por_id IS NOT NULL
                AND resolvido_em >= criado_em
            )
        ),

    CONSTRAINT ck_alerta_acao_tomada
        CHECK (
            acao_tomada IS NULL
            OR (
                status = 'RESOLVIDO'
                AND acao_tomada IN ('AJUSTOU', 'TRANSFERIU_LOTE', 'DESCARTOU')
            )
        )
);

-- 6. LOTE
CREATE TABLE lote (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instituicao_id BIGINT NOT NULL,
    descricao VARCHAR(200) NOT NULL,
    categoria VARCHAR(80) NOT NULL,
    kg NUMERIC(10,2) NOT NULL,
    validade DATE NOT NULL,
    status VARCHAR(12) NOT NULL DEFAULT 'DISPONIVEL',
    retirado_em TIMESTAMPTZ,

    CONSTRAINT fk_lote_instituicao
        FOREIGN KEY (instituicao_id)
        REFERENCES instituicao (id)
        ON DELETE RESTRICT,

    CONSTRAINT ck_lote_kg
        CHECK (kg > 0),

    CONSTRAINT ck_lote_status
        CHECK (
            status IN (
                'DISPONIVEL',
                'DISTRIBUIDO',
                'PERDIDO'
            )
        ),

    -- Lote disponivel nao tem retirada; lote que saiu (distribuido ou perdido)
    -- tem data de retirada. Sem isso a CONSULTA 1 (kg doados) descartaria
    -- em silencio um lote marcado como DISTRIBUIDO sem data.
    CONSTRAINT ck_lote_retirada_coerente
        CHECK (
            (status = 'DISPONIVEL' AND retirado_em IS NULL)
            OR
            (status IN ('DISTRIBUIDO', 'PERDIDO') AND retirado_em IS NOT NULL)
        )
);

-- INDICES OBRIGATORIOS

CREATE INDEX idx_leitura_equipamento_registrada_em
    ON leitura (equipamento_id, registrada_em DESC);

CREATE INDEX idx_alerta_status
    ON alerta (status);

-- Usado pelas CONSULTAS 2 e 3 (filtro por equipamento + periodo de criacao)
CREATE INDEX idx_alerta_equipamento_criado_em
    ON alerta (equipamento_id, criado_em DESC);

-- INDICES ADICIONAIS

CREATE INDEX idx_equipamento_instituicao
    ON equipamento (instituicao_id);

CREATE INDEX idx_lote_instituicao
    ON lote (instituicao_id);

COMMIT;
